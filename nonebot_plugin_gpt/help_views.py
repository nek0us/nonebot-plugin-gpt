def format_help(topic: str = "") -> str:
    """返回指定主题的帮助；未知主题给出可选项，避免发送过长全文。"""
    section = _ALIASES.get(topic.strip().lower())
    if section is None:
        return "未找到该帮助主题。可用主题：会话、人设、模型、管理、授权、智能体。"
    return _HELP_SECTIONS[section]
